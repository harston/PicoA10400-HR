#!/usr/bin/env python3
"""Build the PicoA10400-HR menu kernel (bank 0 of the 32-column menu).

menu32_hr.asm is the PlusCart menu kernel (ORIG/United-Carts-of-Atari, GPL-3)
with ONE change: a cursor report the PicoA10400 needs for the marquee
(`lda MARQUEE_REPORT,x` in SetActiveItem, three bytes). Everything else has to
stay byte-identical to the base, and this script is what proves it:

  1. the UPSTREAM file is assembled here and must reproduce the shipped
     firmware_{ntsc,pal}_rom.h arrays byte for byte - if that fails, the
     toolchain or the sources moved and nothing below can be trusted;
  2. our revision is diffed against that build and must differ ONLY by the
     three inserted bytes (and the shift they cause);
  3. the addresses the page generator needs (DoStart, ContDrawScreen, ...) are
     read from the assembler's symbol table, never copied by hand - PlusCart's
     own firmware carries a stale `jmp $106B` for DoStart, which is $1077 in
     this revision.

Output: <sketch>/menu32_rom.h (PAL) and <sketch>/menu32_rom_ntsc.h for both
sketches, identical files, in the same shape as rom.h: a byte array plus the
constants. build.sh swaps the NTSC file in, exactly as it does for rom.h.

Usage: python3 menu32_rom/build_menu32_rom.py [--check]   (--check: no writing)
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
UPSTREAM = ROOT / "ORIG" / "United-Carts-of-Atari" / "source" / "Atari2600ROM" / "PlusCart.asm"
PLUSCART_INC = ROOT / "ORIG" / "United-Carts-of-Atari" / "source" / "STM32firmware" / "PlusCart" / "Inc"
SKETCHES = [ROOT / "PicoA10400", ROOT / "Pico2A10400"]

SWITCH = "NTSC        = 1\nPAL60       = 0\nPAL50       = 0"
TV = {
    "ntsc": SWITCH,
    "pal": "NTSC        = 0\nPAL60       = 0\nPAL50       = 1",
}
# The cursor report: three bytes, LDA $1FC0,X, inserted before the RTS of
# SetActiveItem, which is the last routine in bank 0.
INSERT = bytes([0xBD, 0xC0, 0x1F])

NEEDED_SYMBOLS = ["FirstStart", "DoStart", "ContDrawScreen", "SwitchBank", "ExitKernel"]
# Symbols only our revision has, so the firmware can patch bytes inside the kernel
# instead of this script having to rebuild it for every colour change.
HR_SYMBOLS = ["HRSelCol", "HRHeaderCol", "HRHeaderCol2", "HRBackCol", "HRBackCol2",
              "PlusLogoAnimation"]


def shipped(name: str) -> bytes:
    text = (PLUSCART_INC / name).read_text()
    body = text[text.index("{") + 1:text.rindex("}")]
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))


def assemble(source: Path, tv: str, work: Path) -> tuple[bytes, dict[str, int]]:
    work.mkdir(parents=True, exist_ok=True)
    text = source.read_text(encoding="utf-8", errors="surrogateescape")
    if SWITCH not in text:
        sys.exit(f"{source.name}: the NTSC/PAL60/PAL50 switch block is not where it was - source moved?")
    src = work / f"{source.stem}_{tv}.asm"
    src.write_text(text.replace(SWITCH, TV[tv], 1), encoding="utf-8", errors="surrogateescape")
    for extra in ("vcs.h", "SmallCaps.asm", "Trichotomic-12.asm", "CaptainMorgan.asm", "GlacierBelle.asm"):
        (work / extra).write_bytes((source.parent / extra).read_bytes())
    out, sym = work / f"{tv}.bin", work / f"{tv}.sym"
    r = subprocess.run(["dasm", src.name, "-f3", f"-o{out}", f"-s{sym}"], cwd=work,
                       capture_output=True, text=True)
    if r.returncode != 0 or not out.exists():
        sys.exit(f"dasm failed for {source.name} ({tv}):\n{r.stdout}\n{r.stderr}")
    size = int(re.search(r"SIZE=\s*(\d+)", r.stdout).group(1))
    symbols = {}
    for line in sym.read_text().splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0] in NEEDED_SYMBOLS + HR_SYMBOLS:
            symbols[parts[0]] = int(parts[1], 16)
    missing = [s for s in NEEDED_SYMBOLS if s not in symbols]
    if missing:
        sys.exit(f"symbols missing from {sym}: {missing}")
    return out.read_bytes()[:size], symbols


def header(name: str, code: bytes, sym: dict[str, int], tv: str) -> str:
    rows = []
    for i in range(0, len(code), 12):
        rows.append("  " + " ".join("0x%02X," % b for b in code[i:i + 12]))
    return f"""// {name} - bank 0 of the 32-column menu ({tv.upper()}), generated by
// menu32_rom/build_menu32_rom.py from menu32_rom/menu32_hr.asm. Do not edit by
// hand: the script also proves that the same sources rebuild PlusCart's shipped
// template byte for byte, so a difference here is always our difference.
//
// PlusCart menu kernel, (C) the United Carts of Atari project, GPL-3; our only
// change is the cursor report (`lda $1FC0,x` in SetActiveItem) that feeds the
// PicoA10400 marquee.
#ifndef MENU32_ROM_H
#define MENU32_ROM_H

// Addresses inside the kernel, read from the assembler's symbol table.
#define MENU32_ROM_FIRSTSTART     0x{sym['FirstStart']:04X}  // reset vector target
#define MENU32_ROM_DOSTART        0x{sym['DoStart']:04X}  // menu main loop
#define MENU32_ROM_CONTDRAWSCREEN 0x{sym['ContDrawScreen']:04X}  // after a page's kernel
#define MENU32_ROM_SWITCHBANK     0x{sym['SwitchBank']:04X}  // sta $FFF5,x stub
#define MENU32_ROM_EXITKERNEL     0x{sym['ExitKernel']:04X}  // cld / sta $FFF4 stub

// Bytes the firmware patches in its copy of the kernel (menu32.h): the cursor
// colour is the operand of `lda #SEL_COL` in SetActiveItem, and the wait-routine
// animation is PlusCart's logo, which we do not put on someone else's menu.
#define MENU32_ROM_SELCOL_OFF     0x{sym['HRSelCol'] - 0x1000 + 1:04X}
#define MENU32_ROM_HEADCOL_OFF    0x{sym['HRHeaderCol'] - 0x1000 + 1:04X}
#define MENU32_ROM_HEADCOL2_OFF   0x{sym['HRHeaderCol2'] - 0x1000 + 1:04X}
#define MENU32_ROM_BACKCOL_OFF    0x{sym['HRBackCol'] - 0x1000 + 1:04X}
#define MENU32_ROM_BACKCOL2_OFF   0x{sym['HRBackCol2'] - 0x1000 + 1:04X}
#define MENU32_ROM_LOGO_OFF       0x{sym['PlusLogoAnimation'] - 0x1000:04X}
#define MENU32_ROM_LOGO_SIZE      32    // four frames of eight rows

static const unsigned char menu32_rom[{len(code)}] = {{
{chr(10).join(rows)}
}};

#endif
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only, write nothing")
    args = ap.parse_args()

    ok = True
    written = []
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for tv, shipped_name in (("ntsc", "firmware_ntsc_rom.h"), ("pal", "firmware_pal_rom.h")):
            base, base_sym = assemble(UPSTREAM, tv, work / f"up_{tv}")
            ref = shipped(shipped_name)
            if base != ref:
                print(f"FAIL {tv}: our build of the upstream kernel is not the shipped {shipped_name}"
                      f" ({len(base)} vs {len(ref)} bytes)")
                ok = False
                continue
            print(f"OK   {tv}: upstream rebuild == {shipped_name} ({len(base)} bytes)")

            ours, sym = assemble(HERE / "menu32_hr.asm", tv, work / f"hr_{tv}")
            cut = len(ours) - len(base)
            at = next((i for i in range(min(len(base), len(ours))) if base[i] != ours[i]), None)
            expected = (cut == len(INSERT) and at is not None
                        and ours[at:at + len(INSERT)] == INSERT
                        and ours[at + len(INSERT):] == base[at:])
            if not expected:
                print(f"FAIL {tv}: our revision differs from the base in more than the cursor report")
                ok = False
                continue
            print(f"OK   {tv}: revision = base + {len(INSERT)} bytes {INSERT.hex()} at $%04X" % (0x1000 + at))
            for lbl in ("HRSelCol", "HRHeaderCol", "HRHeaderCol2", "HRBackCol", "HRBackCol2"):
                at = sym[lbl] - 0x1000
                if ours[at] != 0xA9:
                    print(f"FAIL {tv}: {lbl} does not point at `lda #` ({ours[at]:02X})")
                    ok = False
            for name in NEEDED_SYMBOLS:
                if sym[name] != base_sym[name]:
                    print(f"FAIL {tv}: symbol {name} moved ({base_sym[name]:04X} -> {sym[name]:04X})")
                    ok = False
            if not ok:
                continue

            fname = "menu32_rom.h" if tv == "pal" else "menu32_rom_ntsc.h"
            text = header(fname, ours, sym, tv)
            print(f"     {fname}: {len(ours)} bytes, md5 {hashlib.md5(ours).hexdigest()}, "
                  f"DoStart=${sym['DoStart']:04X} ContDrawScreen=${sym['ContDrawScreen']:04X}")
            if not args.check:
                for sketch in SKETCHES:
                    (sketch / fname).write_text(text)
                    written.append(str((sketch / fname).relative_to(ROOT)))
    for w in written:
        print("wrote", w)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
